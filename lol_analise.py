from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler
from imblearn.over_sampling import SMOTE
from sklearn.model_selection import train_test_split
from sklearn.metrics import confusion_matrix
import seaborn as sns
import matplotlib.pyplot as plt

# 1. Garantir que a coluna 'lado_mapa' está traduzida e selecionar as features
dados_modelo['lado_mapa'] = dados_modelo['side'].map({'Blue': 0, 'Red': 1})
features_novas = ["golddiffat10", "golddiffat15", "evolucao_ouro", "killsat10", "killsat15", "lado_mapa"]

X_novo = dados_modelo[features_novas]
y_novo = dados_modelo["result"]

# 2. Dividir os dados em treino e teste
X_treino_n, X_teste_n, y_treino_n, y_teste_n = train_test_split(X_novo, y_novo, test_size=0.3, random_state=42)

# 3. Padronizar a escala (essencial para a Rede Neural)
scaler_n = StandardScaler()
X_treino_esc_n = scaler_n.fit_transform(X_treino_n)
X_teste_esc_n = scaler_n.transform(X_teste_n)

# 4. Aplicar o SMOTE para equilibrar os dados de treino (50/50)
smote_n = SMOTE(random_state=42)
X_treino_bal_n, y_treino_bal_n = smote_n.fit_resample(X_treino_esc_n, y_treino_n)

# 5. Criar e treinar a Rede Neural turbinada
modelo_rn_mapa = MLPClassifier(hidden_layer_sizes=(10, 5), max_iter=1000, random_state=42)
modelo_rn_mapa.fit(X_treino_bal_n, y_treino_bal_n)

# 6. Testar o modelo e desenhar a Matriz de Confusão
previsoes_rn_mapa = modelo_rn_mapa.predict(X_teste_esc_n)
matriz_rn_mapa = confusion_matrix(y_teste_n, previsoes_rn_mapa)

sns.heatmap(matriz_rn_mapa, annot=True, fmt='d', cmap='Blues')
plt.title('Rede Neural com SMOTE + Lado do Mapa')
plt.xlabel('O que a IA Previu (0 = Derrota, 1 = Virada)')
plt.ylabel('Realidade (0 = Derrota, 1 = Virada)')
plt.show()

